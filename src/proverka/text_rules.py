def normalize_text(text: str) -> tuple[str, int]:
    """
    Готовит текст к поиску признаков:
      1. NFKC-нормализация Unicode: «ｓｂｅｒ» (широкие буквы) → «sber».
      2. Слова, где перемешаны кириллица и латиница (например, «Сбeрбанк» с
         латинской «e»), переводим целиком в кириллицу — так шаблоны
         правил сработают, даже если мошенник пытался их обойти.
      3. Нижний регистр, «ё» → «е».

    Возвращает (нормализованный_текст, сколько_найдено_слов-хамелеонов).
    """
    text = unicodedata.normalize("NFKC", text)

    mixed_count = 0

    def fix_word(match: re.Match[str]) -> str:
        nonlocal mixed_count
        word = match.group()
        has_cyr = any("а" <= ch.lower() <= "я" or ch in "ёЁ" for ch in word)
        has_lat = any("a" <= ch.lower() <= "z" for ch in word)
        if has_cyr and has_lat:
            # Считаем «хамелеоном», только если ВСЕ латинские буквы слова
            # имеют кириллического двойника. Иначе это может быть честное
            # сочетание вроде «iPhone-чехол» или «Wi-Fi-роутер».
            latin = [ch for ch in word if "a" <= ch.lower() <= "z"]
            if all(ch in LATIN_TO_CYRILLIC for ch in latin):
                mixed_count += 1
                return "".join(LATIN_TO_CYRILLIC.get(ch, ch) for ch in word)
        return word

    # \w+ — одно «слово» без пробелов; вложенных повторений нет.
    text = re.sub(r"\w+", fix_word, text)
    # Переносы строк и лишние пробелы → один пробел. Иначе шаблоны вида
    # «.{0,30}» (точка не захватывает перенос строки) не сработают, если
    # фраза разбита на строки — а так почти всегда бывает в СМС и скриншотах.
    text = re.sub(r"\s+", " ", text)
    text = text.lower().replace("ё", "е")
    return text, mixed_count


def find_text_signals(normalized_text: str) -> list[TextRule]:
    """Возвращает список сработавших правил (каждое не более одного раза)."""
    return [
        rule
        for rule in TEXT_RULES
        if any(p.search(normalized_text) for p in rule.patterns)
    ]
