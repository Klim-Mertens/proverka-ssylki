"""
Правила-признаки мошенничества в ТЕКСТЕ сообщения.

Как это устроено:
  * Текст приводится к «нормальному» виду: нижний регистр, «ё» → «е»,
    латинские буквы-двойники внутри русских слов → кириллица.
  * Каждое правило — это набор коротких шаблонов (регулярных выражений)
    и объяснение простыми словами. Если сработал хотя бы один шаблон —
    правило считается найденным.
  * У каждого правила есть «вес» (0–100): насколько сильно этот признак
    говорит о мошенничестве. Веса подобраны вручную и их можно менять.

Почему правила, а не «искусственный интеллект»: правила понятны — всегда
видно, ПОЧЕМУ программа так решила, и это можно объяснить пожилому человеку.

Безопасность регулярных выражений: шаблоны ниже простые — без вложенных
повторений вида (a+)+, поэтому не подвержены ReDoS. Повторения вида \\w*
ограничены одним словом.
"""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass

from .data import LATIN_TO_CYRILLIC


@dataclass(frozen=True)
class TextRule:
    rule_id: str        # короткий идентификатор (для тестов и статистики)
    weight: int         # вес признака 0–100
    explanation: str    # объяснение для человека, простыми словами
    patterns: tuple[re.Pattern[str], ...]


def _rule(rule_id: str, weight: int, explanation: str, *patterns: str) -> TextRule:
    """Вспомогательная функция: компилирует шаблоны один раз при загрузке."""
    return TextRule(rule_id, weight, explanation, tuple(re.compile(p) for p in patterns))


