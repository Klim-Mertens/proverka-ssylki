# Текст кнопки (и короткая команда) → ответ.
MEMOS: dict[str, str] = {
    BTN_SOS: SOS_TEXT,
    "/sos": SOS_TEXT,
    BTN_SIGNS: SIGNS_TEXT,
    "/priznaki": SIGNS_TEXT,
    BTN_PHONES: PHONES_TEXT,
    "/telefony": PHONES_TEXT,
}


def memo_for(text: str) -> str | None:
    """Ответ-памятка, если человек нажал кнопку (или ввёл команду). Иначе None."""
    key = text.strip()
    if key.startswith("/"):
        key = key.split(maxsplit=1)[0].split("@")[0].lower()
    return MEMOS.get(key)
